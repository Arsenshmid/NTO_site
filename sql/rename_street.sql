/* =====================================================================
   ПЕРЕИМЕНОВАНИЕ УЛИЦЫ В БАЗЕ AvtodorDB
   "Автодорожная" → "Проспект Михаила Николаева"

   Обновляет колонку Street во всех домах, где улица = "Автодорожная"
   (без учёта регистра и пробелов по краям).
   Колонка FullAddress (если она вычисляемая) обновится автоматически —
   она считается из Street + ', ' + HouseNo.

   Выполнять в SSMS при подключении к базе AvtodorDB!
   Безопасно для повторного запуска: если улица уже переименована,
   обновится 0 строк (можно проверять).

   Дополнительно: обновляет и UKName, если в названии УК фигурирует
   "Автодорожная" (маловероятно, но проверим).
   ===================================================================== */
USE AvtodorDB;
GO
SET NOCOUNT ON;
PRINT N'--- Переименование улицы «Автодорожная» → «Проспект Михаила Николаева» ---';

-- 1) Покажем, сколько домов сейчас с этой улицей
DECLARE @before INT;
SELECT @before = COUNT(*) FROM dbo.House
 WHERE LTRIM(RTRIM(LOWER(Street))) = N'автодорожная';
PRINT N'Найдено домов с улицей «Автодорожная»: ' + CAST(@before AS NVARCHAR(10));
GO

-- 2) Обновим Street. Учитываем регистр: «автодорожная», «Автодорожная», «АВТОДОРОЖНАЯ»
--    ( LOWER() + LTRIM(RTRIM()) для надёжности)
UPDATE dbo.House
   SET Street = N'Проспект Михаила Николаева'
 WHERE LTRIM(RTRIM(LOWER(Street))) = N'автодорожная';
PRINT N'Обновлено строк: ' + CAST(@@ROWCOUNT AS NVARCHAR(10));
GO

-- 3) Проверим результат — должны увидеть новые адреса
PRINT N'';
PRINT N'--- Результат: дома с новой улицей ---';
SELECT TOP 20 HouseID, Street, HouseNo, FullAddress, Lat, Lon
  FROM dbo.House
 WHERE Street = N'Проспект Михаила Николаева'
 ORDER BY HouseNo;
GO

-- 4) Проверим, не осталось ли «Автодорожная» (должно быть 0)
DECLARE @left INT;
SELECT @left = COUNT(*) FROM dbo.House
 WHERE LTRIM(RTRIM(LOWER(Street))) = N'автодорожная';
IF @left = 0
  PRINT N'✓ Все дома с улицей «Автодорожная» переименованы.';
ELSE
  PRINT N'ВНИМАНИЕ: осталось ' + CAST(@left AS NVARCHAR(10)) + N' домов с улицей «Автодорожная». Проверьте вручную.';
GO

PRINT N'';
PRINT N'=== Готово. Перезапустите сайт (python app.py) и обновите страницу (Ctrl+F5). ===';
PRINT N'На карте и в списке МКД адреса обновятся автоматически.';
